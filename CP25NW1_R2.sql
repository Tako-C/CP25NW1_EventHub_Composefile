-- 13. EVENT_REWARDS
-- ========================================
BEGIN
   EXECUTE IMMEDIATE 'CREATE TABLE EVENT_REWARD (
       ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
       NAME VARCHAR2(100),
       DESCRIPTION VARCHAR2(150),
       EVENT_ID NUMBER NOT NULL,
       REQUIREMENT_TYPE VARCHAR2(20) DEFAULT ''FREE'' 
           CHECK (REQUIREMENT_TYPE IN (''FREE'', ''CHECKED_IN'', ''PRE_SURVEY_DONE'', ''POST_SURVEY_DONE'')),
       START_REDEEM_AT  TIMESTAMP,
       END_REDEEM_AT    TIMESTAMP,
       QUANTITY NUMBER DEFAULT 0,
       STATUS VARCHAR2(15) DEFAULT ''ACTIVE'' 
           CHECK (STATUS IN (''ACTIVE'', ''INACTIVE'', ''OUT_OF_STOCK'')),
       CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
       UPDATED_AT TIMESTAMP,
       CONSTRAINT FK_EVENT_REWARD_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(ID)
   )';
EXCEPTION 
   WHEN OTHERS THEN 
      DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM);
END;
/
COMMIT;




