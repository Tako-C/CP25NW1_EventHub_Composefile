-- ========================================
-- 4. USERS
-- ========================================
-- M = Male, F = Female, U = Unknown, N = Not Applicable
BEGIN
   EXECUTE IMMEDIATE 'CREATE TABLE USERS (
       ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
       FIRST_NAME VARCHAR2(100) NOT NULL,
       LAST_NAME VARCHAR2(100) NOT NULL,
       EMAIL VARCHAR2(150) NOT NULL,
       PASSWORD VARCHAR2(255) NOT NULL,
       DATE_OF_BIRTH DATE ,
       GENDER CHAR(1) DEFAULT ''N'' CHECK (ROLE IN (''M'', ''F'', ''U'', ''N'')),
       ROLE VARCHAR2(12) DEFAULT ''GENERAL_USER'' CHECK (ROLE IN (''GENERAL_USER'', ''ADMIN'')),
       PHONE VARCHAR2(10),
       JOB_ID NUMBER,
       ADDRESS VARCHAR2(200),
       COUNTRIES_ID NUMBER,
       CITIES_ID NUMBER,
       POST_CODE VARCHAR2(10),
       IMG_PATH_PROF VARCHAR2(150),
       STATUS VARCHAR2(8) DEFAULT ''ACTIVE'' CHECK (STATUS IN (''ACTIVE'', ''INACTIVE'')),
       CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
       UPDATED_AT TIMESTAMP,
       CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
       CONSTRAINT FK_USERS_JOB FOREIGN KEY (JOB_ID) REFERENCES JOBS(ID),
       CONSTRAINT FK_USERS_COUNTRIES FOREIGN KEY (COUNTRIES_ID) REFERENCES COUNTRIES(ID),
       CONSTRAINT FK_USERS_CITIES FOREIGN KEY (CITIES_ID) REFERENCES CITIES(ID)
   )';
EXCEPTION 
   WHEN OTHERS THEN NULL; 
END;
/
COMMIT;

